def build_catalogs():
    targets = [
        BASE_DIR / "translations",
        BASE_DIR / "templates" / "translations",
    ]

    for target_dir in targets:
        ar_dir = target_dir / "ar" / "LC_MESSAGES"
        fr_dir = target_dir / "fr" / "LC_MESSAGES"
        ar_dir.mkdir(parents=True, exist_ok=True)
        fr_dir.mkdir(parents=True, exist_ok=True)

        # Arabic Catalog
        cat_ar = Catalog(locale="ar", domain="messages")
        for orig, trans in ARABIC_MESSAGES.items():
            cat_ar.add(orig, trans)

        po_path_ar = ar_dir / "messages.po"
        mo_path_ar = ar_dir / "messages.mo"

        with open(po_path_ar, "wb") as f:
            pofile.write_po(f, cat_ar, omit_header=False)

        with open(mo_path_ar, "wb") as f:
            mofile.write_mo(f, cat_ar)

        # French Catalog (identity)
        cat_fr = Catalog(locale="fr", domain="messages")
        for orig in ARABIC_MESSAGES.keys():
            cat_fr.add(orig, orig)

        po_path_fr = fr_dir / "messages.po"
        mo_path_fr = fr_dir / "messages.mo"

        with open(po_path_fr, "wb") as f:
            pofile.write_po(f, cat_fr, omit_header=False)

        with open(mo_path_fr, "wb") as f:
            mofile.write_mo(f, cat_fr)

    print(f"Catalogues générés avec succès pour {len(ARABIC_MESSAGES)} messages.")


if __name__ == "__main__":
    build_catalogs()
